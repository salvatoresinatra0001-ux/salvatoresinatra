import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = process.cwd();
const html = fs.readFileSync(path.join(root,'index.html'),'utf8');
const js = fs.readFileSync(path.join(root,'assets/site.js'),'utf8');
const css = fs.readFileSync(path.join(root,'assets/site.css'),'utf8');
const expected = ['home','identita','framework','portfolio','visual-arts','formazione','technology','music','projects','directory','archive','contatti'];
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
const links = [...html.matchAll(/href="#([^"]+)"/g)].map(m => m[1]);
const images = [...html.matchAll(/<img\b[^>]*>/g)].map(m => m[0]).filter(tag => /\bsrc=/.test(tag));
const sources = images.map(tag => tag.match(/\bsrc="([^"]+)"/)?.[1]).filter(Boolean);
const text = html.replace(/<script[\s\S]*?<\/script>/g,' ').replace(/<[^>]+>/g,' ').replace(/&[a-z]+;/g,' ');
const words = text.split(/\s+/).filter(Boolean).length;
const failures = [];
function check(name,fn){try{fn();console.log('PASS',name);}catch(e){failures.push(name+': '+e.message);console.error('FAIL',name,e.message);}}
check('all 12 canonical sections',()=>{for(const id of expected)assert.ok(ids.includes(id),'Missing '+id);});
check('unique HTML ids',()=>assert.equal(ids.length,new Set(ids).size));
check('internal anchor targets',()=>{for(const target of links)assert.ok(target==='top'||ids.includes(target),'Missing '+target);});
check('photographic assets exist',()=>{assert.equal(images.length,7);for(const src of sources)assert.ok(fs.existsSync(path.join(root,src)),src);});
check('all photographs have descriptive alt',()=>{for(const img of images)assert.match(img,/\balt="[^"]{8,}"/);});
check('no synthetic photography sources',()=>assert.doesNotMatch(html,/unsplash|pexels|placeholder\.com|imagegen|stock-photo/i));
check('no sensitive personal information',()=>assert.doesNotMatch(html,/9 marzo 1990|aripiprazol|schizoaffett|balbuz|litio/i));
check('academic status is accurate',()=>{assert.match(html,/L-24/);assert.match(html,/studente/i);});
check('photographic series and archival cards',()=>{for(const s of ['NOIRVEIL','STILL ECHOES','TRUE MONOCHROME','SAMYA \/ 01','MONOCROMATICO \/ 05'])assert.ok(html.includes(s),s);});
check('functional controls',()=>{for(const x of ['portfolio-search','directory-search','photo-dialog','data-photo-filter','data-dir-filter'])assert.ok(html.includes(x),x);});
check('monochrome design and motion reduction',()=>{assert.match(css,/prefers-reduced-motion/);assert.match(css,/--black:/);});
check('JS implementation',()=>{for(const x of ['showModal','updatePhotos','updateDirectory','aria-pressed'])assert.ok(js.includes(x),x);});
check('expanded editorial copy ~5x',()=>assert.ok(words >= 7145,'Only '+words+' words; target >= 7145'));
check('no inline styling',()=>assert.doesNotMatch(html,/\sstyle="/));
console.log('\nAtlas 3.0 audit:',{words,ratio:(words/1429).toFixed(2),images:images.length,sections:expected.length,failures:failures.length});
if(failures.length)process.exitCode=1;